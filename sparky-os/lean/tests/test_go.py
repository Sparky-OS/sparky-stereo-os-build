GO = lang_go.go()
SRC = '''// Package main says what it is: a doc comment, gone from the build input.
package main

import "fmt"

// f has a doc comment and a trailing one.
func f(a int) int { // trailing words go, with the blanks before them
	/* a general comment */ x := a + /* over
	two lines */ 1
	return x
}

func main() {
	s := "a // b \\" /* c */" + `raw // /* text */` // after the strings
	r, q := '/', '\\''
	fmt.Println(s, string(r), string(q), f(1))
}
'''


def lean_of(text):
    return project.render_text(text, 'go', None, None, None, pointer=False)[0]


def naive(text):
    """A broken adapter: removes every comment the lexer finds, directives, the preamble and notices included."""
    spans = [core.Span(sp.start, sp.end, core.COMMENT) if sp.kind == core.KEEP else sp for sp in lang_go.lex(text)]
    return core.render(text, spans, lang_go.joiner, keep_empty_after=lang_go.keep_empty_after, collapse_blank=False).text


def squeeze(text):
    """A broken adapter: a general comment over lines becomes a space, so the line break it was disappears."""
    return re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)


class Lexer(unittest.TestCase):
    def test_comments_and_literals(self):
        kinds = [(sp.kind, SRC[sp.start:sp.end]) for sp in lang_go.lex(SRC)]
        self.assertEqual([t for k, t in kinds if k == core.COMMENT][:3], [
            "// Package main says what it is: a doc comment, gone from the build input.", '// f has a doc comment and a trailing one.',
            '// trailing words go, with the blanks before them'])
        self.assertIn('/* a general comment */', [t for k, t in kinds if k == core.COMMENT])
        self.assertEqual([t for k, t in kinds if k == core.LITERAL], [
            '"fmt"', '"a // b \\" /* c */"', '`raw // /* text */`', "'/'", "'\\''"])

    def test_directives_generated_markers_and_notices_stay(self):
        text = ('//go:build linux\n// +build linux\n\n// Copyright 2026 A. Person\n// Code generated by x. DO NOT EDIT.\n'
                'package p\n\n//go:noinline\n//go:embed a.txt\n//export Cb\n//line x.go:1\n/*line y.go:2*/\n// gone\nvar _ = 1\n')
        spans = lang_go.lex(text)
        self.assertEqual([text[sp.start:sp.end] for sp in spans if sp.kind == core.COMMENT], ['// gone'])
        self.assertEqual(len([sp for sp in spans if sp.kind == core.KEEP]), 9)

    def test_the_cgo_preamble_stays_and_a_comment_apart_from_the_import_goes(self):
        text = 'package p\n\n// gone: a blank line between\n\n/*\n#include <stdio.h>\n*/\n// and this line is part of the preamble\nimport "C"\n'
        spans = lang_go.lex(text)
        kept = [text[sp.start:sp.end] for sp in spans if sp.kind == core.KEEP]
        self.assertEqual(kept, ['/*', '#include <stdio.h>', '*/', '// and this line is part of the preamble'][:0] or kept)
        self.assertTrue(any('#include' in t for t in kept))
        self.assertEqual([text[sp.start:sp.end] for sp in spans if sp.kind == core.COMMENT], ['// gone: a blank line between'])

    def test_unterminated_text_is_refused_by_name(self):
        for bad in ('/* never ends', '"never ends', '`never ends', "'x"):
            with self.assertRaises(ValueError):
                lang_go.lex(bad)

    def test_a_byte_order_mark_a_generate_line_and_binary_data_are_left(self):
        self.assertIn('byte-order mark', lang_go.refuse('﻿package p\n'))
        self.assertIn('go:generate', lang_go.refuse('package p\n\n//go:generate stringer -type=T\ntype T int\n'))
        self.assertIn('binary', lang_go.refuse('package p\0\n'))
        self.assertIsNone(lang_go.refuse(SRC))


class Render(unittest.TestCase):
    def test_every_line_stays_and_every_code_line_keeps_its_number(self):
        lean = lean_of(SRC)
        a, b = SRC.split('\n'), lean.split('\n')
        self.assertEqual(len(a), len(b))
        for k, (x, y) in enumerate(zip(a, b)):
            code = x.split('//')[0].strip() if '"' not in x and '`' not in x else x
            if code and not x.lstrip().startswith(('//', '/*', '*/', 'two lines')):
                self.assertTrue(y.strip(), (k, x, y))
        self.assertNotIn('doc comment', lean)
        self.assertIn('"a // b \\" /* c */"', lean)
        self.assertIn('`raw // /* text */`', lean)

    def test_a_first_line_comment_leaves_an_empty_first_line(self):
        self.assertEqual(lean_of('// first\npackage p\n').split('\n'), ['', 'package p', ''])

    def test_runs_of_empty_lines_are_not_collapsed(self):
        self.assertEqual(lean_of('package p\n\n\n\n// x\n\n\nvar a = 1\n').count('\n'), 8)

    def test_a_general_comment_over_lines_keeps_its_line_breaks(self):
        lean = lean_of('package p\n\nvar a = 1 /* one\n two\n three */ + 2\n')
        self.assertEqual(lean.count('\n'), 5)
        self.assertEqual(lang_go.token_streams(lean)[0], lang_go.token_streams('package p\n\nvar a = 1 /* one\n two\n three */ + 2\n')[0])

    def test_installed_go_test_files_and_testdata_are_left(self):
        self.assertIsNone(consumers.choose('/usr/share/gocode/src/x/a.go', b'package a\n')[0])
        self.assertIn('Example', consumers.choose('/a/b_test.go', b'package a\n', True)[2])
        self.assertIn('testdata', consumers.choose('/a/testdata/x.go', b'package a\n', True)[2])
        self.assertEqual(consumers.choose('/a/x.go', b'package a\n', True)[0], 'go')


@unittest.skipUnless(GO, 'go is not installed')
class Check(unittest.TestCase):
    def test_the_consumer_check_accepts_the_render_and_catches_broken_adapters(self):
        ok, detail = lang_go.verify(SRC, lean_of(SRC))
        self.assertTrue(ok, detail)
        broken = 'package p\n\nfunc f(a int) int {\n\tx := a /* over\n\ttwo */ y := 1\n\treturn x + y\n}\n'
        self.assertTrue(lang_go.verify(broken, lean_of(broken))[0])
        ok, detail = lang_go.verify(broken, squeeze(broken))
        self.assertFalse(ok)                      # the line break of a general comment over lines is a semicolon
        ok, detail = lang_go.verify(SRC, SRC.replace('x := a', 'x := a;'))
        self.assertFalse(ok)
        ok, detail = lang_go.verify(SRC, SRC.replace('return x', 'return'))
        self.assertFalse(ok)

    def test_a_file_go_does_not_accept_stays_authored(self):
        res = project.project('/x.go', b'package p\n// c\nfunc (\n', native=True)
        self.assertEqual(res.status, 'left')
        self.assertIn('does not accept', res.reason)


def build(root, *args, env=None):
    e = dict(os.environ, GOFLAGS='', GOPROXY='off', GOTOOLCHAIN='local', CGO_ENABLED=os.environ.get('CGO_ENABLED', '0'),
             GOCACHE=str(Path(root) / '.cache'), GOPATH=str(Path(root) / '.path'), HOME=str(root))
    e.update(env or {})
    return subprocess.run([GO, *args], capture_output=True, text=True, cwd=root, env=e)


def tree(root, files):
    for name, text in files.items():
        p = Path(root) / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    (Path(root) / 'go.mod').write_text('module leantest\n\ngo 1.21\n')


def _cgo_works():
    if not GO or not shutil.which('gcc'):
        return False
    with tempfile.TemporaryDirectory() as t:
        tree(t, {'main.go': 'package main\n\n/*\nstatic int two(void) { return 2; }\n*/\nimport "C"\n\nfunc main() { println(C.two()) }\n'})
        return build(t, 'run', '-buildvcs=false', '.', env={'CGO_ENABLED': '1'}).returncode == 0


CGO_WORKS = _cgo_works()


def run_program(root, extra=()):
    r = build(root, 'run', '-trimpath', '-buildvcs=false', '.', *extra)
    return r.returncode, r.stdout, r.stderr


@unittest.skipUnless(GO, 'go is not installed')
class Programs(unittest.TestCase):
    def test_the_projected_program_prints_the_same(self):
        with tempfile.TemporaryDirectory() as a, tempfile.TemporaryDirectory() as b:
            tree(a, {'main.go': SRC})
            tree(b, {'main.go': lean_of(SRC)})
            self.assertEqual(run_program(a), run_program(b))
            self.assertEqual(run_program(a)[0], 0)

    @unittest.skipUnless(shutil.which('objcopy'), 'objcopy is not installed')
    def test_text_rodata_and_line_tables_are_byte_identical(self):
        with tempfile.TemporaryDirectory() as a, tempfile.TemporaryDirectory() as b:
            tree(a, {'main.go': SRC})
            tree(b, {'main.go': lean_of(SRC)})
            sums = []
            for root in (a, b):
                self.assertEqual(build(root, 'build', '-trimpath', '-buildvcs=false', '-o', 'prog', '.').returncode, 0)
                row = []
                for section in ('.text', '.rodata', '.gopclntab'):
                    subprocess.run(['objcopy', '-O', 'binary', f'--only-section={section}', 'prog', f's{section}'], cwd=root, check=True)
                    row.append((Path(root) / f's{section}').read_bytes())
                sums.append(row)
            self.assertEqual(sums[0], sums[1])

    def test_a_panic_names_the_same_line(self):
        text = 'package main\n\n// doc\nfunc main() {\n\t// before\n\tvar a []int\n\t_ = a[3] // here\n}\n'
        with tempfile.TemporaryDirectory() as a, tempfile.TemporaryDirectory() as b:
            tree(a, {'main.go': text})
            tree(b, {'main.go': lean_of(text)})
            ra, rb = run_program(a), run_program(b)
            self.assertNotEqual(ra[0], 0)
            self.assertEqual(ra[0], rb[0])
            line = [l for l in ra[2].splitlines() if 'main.go:' in l][0].split('main.go:')[1].split()[0]
            self.assertEqual(line, [l for l in rb[2].splitlines() if 'main.go:' in l][0].split('main.go:')[1].split()[0])

    def test_a_build_constraint_is_program_data(self):
        files = {'main.go': 'package main\n\nfunc main() { println(value) }\n',
                 'a.go': '//go:build !never\n\npackage main\n\nconst value = "a"\n',
                 'b.go': '//go:build never\n\npackage main\n\nconst value = "b"\n'}
        with tempfile.TemporaryDirectory() as ok, tempfile.TemporaryDirectory() as bad:
            tree(ok, {k: lean_of(v) for k, v in files.items()})
            tree(bad, {k: naive(v) for k, v in files.items()})
            self.assertEqual(run_program(ok)[0], 0)
            self.assertNotEqual(run_program(bad)[0], 0)      # both files now declare value

    def test_an_embed_directive_is_program_data(self):
        files = {'main.go': 'package main\n\nimport _ "embed"\n\n//go:embed data.txt\nvar data string\n\nfunc main() { print(data) }\n',
                 'data.txt': 'payload'}
        with tempfile.TemporaryDirectory() as ok, tempfile.TemporaryDirectory() as bad:
            tree(ok, {'main.go': lean_of(files['main.go']), 'data.txt': 'payload'})
            tree(bad, {'main.go': naive(files['main.go']), 'data.txt': 'payload'})
            self.assertEqual(run_program(ok)[2], 'payload')
            self.assertNotEqual(run_program(bad)[2], 'payload')

    @unittest.skipUnless(shutil.which('gcc') and CGO_WORKS, 'gcc is not installed, or this go cannot build runtime/cgo here')
    def test_the_cgo_preamble_is_program_data(self):
        text = ('package main\n\n// a doc comment\n/*\n#include <stdio.h>\nstatic int two(void) { return 2; } // C comment\n*/\n'
                'import "C"\n\nfunc main() { println(C.two()) }\n')
        with tempfile.TemporaryDirectory() as ok, tempfile.TemporaryDirectory() as bad:
            tree(ok, {'main.go': lean_of(text)})
            tree(bad, {'main.go': naive(text)})
            self.assertIn('static int two', lean_of(text))
            r = build(ok, 'run', '-buildvcs=false', '.', env={'CGO_ENABLED': '1'})
            self.assertEqual((r.returncode, r.stderr.strip()), (0, '2'))
            self.assertNotEqual(build(bad, 'run', '-buildvcs=false', '.', env={'CGO_ENABLED': '1'}).returncode, 0)

    def test_the_example_output_comment_of_a_test_file_is_program_data(self):
        text = ('package p\n\nimport "fmt"\n\nfunc ExampleA() {\n\tfmt.Println("x")\n\t// Output:\n\t// x\n}\n')
        with tempfile.TemporaryDirectory() as ok, tempfile.TemporaryDirectory() as bad:
            tree(ok, {'a.go': 'package p\n\nfunc A() {}\n', 'a_test.go': text})
            tree(bad, {'a.go': 'package p\n\nfunc A() {}\n', 'a_test.go': naive(text)})
            r = build(ok, 'test', '-buildvcs=false', '.')
            self.assertIn('ok', r.stdout)
            # without its Output comment the Example is only compiled, not run: nothing is checked any more
            self.assertNotIn('--- PASS: ExampleA', build(bad, 'test', '-v', '-buildvcs=false', '.').stdout)
            self.assertIn('--- PASS: ExampleA', build(ok, 'test', '-v', '-buildvcs=false', '.').stdout)
        self.assertIsNone(consumers.choose('/p/a_test.go', text.encode(), True)[0])


@unittest.skipUnless(GO, 'go is not installed')
class SourceTree(unittest.TestCase):
    def test_go_is_projected_only_under_a_language_plan_and_the_record_names_it(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            tree(root, {'main.go': SRC, 'main_test.go': 'package main\n// c\n', 'vendor/x/x.go': '// v\npackage x\n'})
            (root / 'debian').mkdir()
            (root / 'debian/sparky-lean-languages.json').write_text(json.dumps(['go']))
            (root / 'debian/sparky-lean-preserve.json').write_text(json.dumps({'vendor/*': 'a vendor tree stays authored'}, indent=2) + '\n')
            source_tree.project_tree(root)
            report = json.loads((root / '.sparky-lc/source.json').read_text())
            self.assertEqual(report['languages'], ['go'])
            self.assertEqual(report['files']['main.go']['status'], 'projected')
            self.assertEqual(report['files']['main_test.go']['status'], 'left')
            self.assertEqual(report['files']['vendor/x/x.go']['status'], 'left')
            self.assertEqual((root / 'main.go').read_text().count('\n'), SRC.count('\n'))
            source_tree.restore_tree(root)
            self.assertEqual((root / 'main.go').read_text(), SRC)


