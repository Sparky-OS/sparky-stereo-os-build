#!/usr/bin/env python3
"""A small Qt 5 window with the usual controls, to see what a Qt 5 program gets from each application style."""
import sys

from PyQt5.QtWidgets import (QApplication, QCheckBox, QComboBox, QGroupBox, QHBoxLayout, QLabel, QLineEdit, QListWidget,
                             QPushButton, QRadioButton, QScrollBar, QTabWidget, QVBoxLayout, QWidget)

app = QApplication(sys.argv)
window = QWidget()
window.setWindowTitle("Qt 5 — " + app.style().objectName())
layout = QVBoxLayout(window)
tabs = QTabWidget()
page = QWidget()
inner = QVBoxLayout(page)
row = QHBoxLayout()
row.addWidget(QPushButton("Button"))
default = QPushButton("Default")
default.setDefault(True)
row.addWidget(default)
combo = QComboBox()
combo.addItems(["Combo box", "Second"])
row.addWidget(combo)
inner.addLayout(row)
group = QGroupBox("Group")
group_layout = QVBoxLayout(group)
group_layout.addWidget(QCheckBox("Check box"))
radio = QRadioButton("Radio button")
radio.setChecked(True)
group_layout.addWidget(radio)
group_layout.addWidget(QLineEdit("Line edit"))
inner.addWidget(group)
inner.addWidget(QScrollBar(1))
lst = QListWidget()
lst.addItems(["List item one", "List item two", "List item three"])
lst.setCurrentRow(1)
inner.addWidget(lst)
tabs.addTab(page, "First")
tabs.addTab(QLabel("Second page"), "Second")
layout.addWidget(tabs)
window.resize(480, 400)
window.show()
sys.exit(app.exec_())
