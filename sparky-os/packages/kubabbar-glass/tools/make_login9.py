def pattern_stops():
    """The progress bar's bands: the Kvantum theme's own pattern (progress-pattern-normal), top to bottom."""
    arr = kv.elements(DEFAULT_ACCENT)["progress-pattern-normal"]
    rows = [hexa(tuple(int(v) for v in arr[y, 0, :3])) for y in range(arr.shape[0])]
    n = len(rows)
    return "\n".join(f'                            GradientStop {{ position: {(i + 0.5) / n:.4f}; color: "{c}" }}'
                     for i, c in enumerate(rows))


