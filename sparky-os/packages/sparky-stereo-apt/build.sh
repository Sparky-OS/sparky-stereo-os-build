# Builds sparky-stereo-apt: the apt source and the pin of the Sparky Stereo OS repository,
# the way SparkyLinux's sparky-apt ships its own. It installs
#   /etc/apt/sources.list.d/sparky-stereo.sources   (deb822, Signed-By the key of sparky-stereo-keyring)
#   /etc/apt/sources.list.d/sparky-stereo-deb-multimedia.sources   (deb-multimedia, forky: the edition's FFmpeg, mpv, x264 and
#                                                     x265 are built on its packages; Signed-By the keyring of its own
#                                                     package, deb-multimedia-keyring, which the Sparky Stereo OS
#                                                     repository carries as deb-multimedia ships it, plus Lean Code's
#                                                     record; it is not blocked, see NOT_OURS in apt/make-only-ours.py)
#   /etc/apt/preferences.d/sparky-stereo-only-ours   (Debian's and deb-multimedia's builds of our
#                                                     packages and Debian's tasks at -1; apt/make-only-ours.py,
#                                                     each name with the architectures we ship it for, and the i386
#                                                     builds of what we ship for amd64 only)
#   /etc/apt/preferences.d/sparky-stereo             (o=Sparky Stereo OS at 1001, its carried NVIDIA 580 user space at -1 until a
#                                                     driver lock raises it; the file is
#                                                     ../../apt/sparky-stereo, its one source)
#   /etc/apt/apt.conf.d/60sparky-stereo-appstream-icons (AppStream's DEP-11 icon downloads enabled)
#   /etc/apt/apt.conf.d/61sparky-install-downloads   (apt's JSON hook that announces install-time downloads on a metered connection, and the
#                                                     setting Sparky::Install-Downloads::Announce; ORDER 399b)
#   /usr/lib/sparky-stereo-apt/install-downloads, sparky_install_downloads.py and the nine languages in
#                                                     /usr/share/sparky/sparky-stereo-apt/install-downloads/ (the one reader of the declaration:
#                                                     apt's hook and Stereo APTus both use them)
#   /usr/lib/sparky-stereo-apt/shadowed-by-dmo, its list /usr/share/sparky-stereo-apt/shadowed-by-dmo.tsv (apt/shadowed.py, generated by
#                                                     make-only-ours.py), /etc/dpkg/dpkg.cfg.d/sparky-stereo-apt (its post-invoke hook) and
#                                                     sparky-stereo-apt-shadowed.service: deb-multimedia's packages that ship files of ours under
#                                                     another name are pinned out in sparky-stereo-only-ours and settled where apt put one (ORDER 458)
# The plain-HTTP block of 20261104.2 to 20261104.3 (/etc/apt/apt.conf.d/00sparky-block-plain-http, ORDER 400) is gone: apt 3.3.6,
# the fix for CVE-2026-109518, is in Debian testing, so this version Depends on it and removes the file (dpkg-maintscript-helper
# rm_conffile in preinst, postinst and postrm, ORDER 413). The conversion of http:// sources to https:// stays (postinst).
# All seven are conffiles (the original four since 20261031.1~sparky9~0, the dpkg hook since 20261109.2; Debian Policy 10.7.3: "local changes must be
# preserved during a package upgrade"); the preinst lets the first upgrade that makes them conffiles replace the files
# nobody changed without a question (debian-scripts/preinst). README.md, shipped in /usr/share/doc, says how a person keeps
# pins of their own without editing these files.
# It depends on sparky-stereo-keyring and on sparky-apt: the edition is built on SparkyLinux
# testing and uses its repository and key too (sparky-apt brings sparky-keyring); we never copy
# their key or files. Likewise deb-multimedia: the package deb-multimedia-keyring brings its key
# (Daniel, 2026-10-08: "we are not debian purists"). Only one package ships the pin for our origin.
# The source is "Types: deb deb-src": the repository publishes main/source/Sources, and the published
# 20261008.1~sparky9~0+lc1 was built that way. DEB_SRC=0 leaves deb-src out, for a repository without a
# source index (apt must not be sent to files that do not exist).
# Needs dpkg-deb, python3 and sparky-stereo-problems (its catalog command builds the journal catalogs of shadowed-by-dmo's messages).
# REPO names what make-only-ours.py reads: a flat repository, a published tree (its dists) or a Packages file.
# Usage: build.sh   (output goes to $OUT, default the current folder)
# Last update 2026/11/09 (ORDER 458)
# Workstation paths come from the local configuration: sparky-os/config/build.conf.example.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-$PWD}
VERSION=${VERSION:-20261110.1~sparky9~0+lc1}
# the oldest sparky-stereo-keyring with the repository's one key (the key has not changed since; 20261016 is published)
KEYRING_VERSION=${KEYRING_VERSION:-20261008.1~sparky9~0+lc1}
PKG=sparky-stereo-apt
TYPES=deb
[ "${DEB_SRC:-1}" = 1 ] && TYPES="deb deb-src"
W=$(mktemp -d "${TMPDIR:-${SPARKY_SCRATCH:?}}/apt-build.XXXXXX")
trap 'rm -rf "${W:?}"' EXIT
D=$W/$PKG
mkdir -p "$D/DEBIAN" "$D/etc/apt/sources.list.d" "$D/etc/apt/preferences.d" "$D/etc/apt/apt.conf.d" "$D/usr/share/doc/$PKG"
install -m644 "$HERE/60sparky-stereo-appstream-icons" "$HERE/61sparky-install-downloads" "$D/etc/apt/apt.conf.d/"
mkdir -p "$D/usr/lib/$PKG" "$D/usr/share/sparky/$PKG/install-downloads" "$D/usr/bin"
install -m755 "$HERE/install-downloads/install-downloads" "$D/usr/lib/$PKG/install-downloads"
install -m644 "$HERE/install-downloads/sparky_install_downloads.py" "$D/usr/lib/$PKG/sparky_install_downloads.py"
install -m644 "$HERE"/install-downloads/lang/*.json "$D/usr/share/sparky/$PKG/install-downloads/"
ln -s "../lib/$PKG/install-downloads" "$D/usr/bin/sparky-install-downloads"
install -m755 "$HERE/lib/shadowed-by-dmo" "$D/usr/lib/$PKG/shadowed-by-dmo"
install -Dm644 "$HERE/../../apt/shadowed-by-dmo.tsv" "$D/usr/share/$PKG/shadowed-by-dmo.tsv"
install -Dm644 "$HERE/systemd/sparky-stereo-apt-shadowed.service" "$D/usr/lib/systemd/system/sparky-stereo-apt-shadowed.service"
install -Dm644 "$HERE/dpkg/sparky-stereo-apt" "$D/etc/dpkg/dpkg.cfg.d/sparky-stereo-apt"

cat >"$D/etc/apt/sources.list.d/sparky-stereo.sources" <<EOS
Types: $TYPES
URIs: https://repo.sparkyos.org/
Suites: mashtabba
Components: main
Signed-By: /etc/apt/trusted.gpg.d/sparky-stereo-repo.asc
EOS
cat >"$D/etc/apt/sources.list.d/sparky-stereo-deb-multimedia.sources" <<'EOS'
# deb-multimedia (https://www.deb-multimedia.org/): the multimedia libraries and players the edition builds on. Our FFmpeg
# and mpv are built on its source packages (ffmpeg-dmo, mpv-dmo) and its x264 and x265 are the ones they use. Its builds of
# the packages we ship are blocked by sparky-stereo-only-ours; the rest of it is there for the edition's other programs.
Types: deb
URIs: https://www.deb-multimedia.org
Suites: forky
Components: main non-free
Signed-By: /usr/share/keyrings/deb-multimedia-keyring.pgp
EOS
cp "$HERE/../../apt/sparky-stereo" "$D/etc/apt/preferences.d/sparky-stereo"
# Debian's and deb-multimedia's builds of our packages, and Debian's tasks, are blocked (generated from the repository index)
# KEEP_ONLY_OURS=1 keeps the file as it is in the tree (a rebuild for a change that does not touch the block list, ORDER 399b);
# the publication round regenerates it over its cohort as before.
if [ "${KEEP_ONLY_OURS:-0}" != 1 ]; then
	python3 "$HERE/../../apt/make-only-ours.py" "${REPO:-${SPARKY_REPO_DIR:?}}" >/dev/null
fi
cp "$HERE/../../apt/sparky-stereo-only-ours" "$D/etc/apt/preferences.d/sparky-stereo-only-ours"
chmod 644 "$D/etc/apt/sources.list.d/sparky-stereo.sources" "$D/etc/apt/sources.list.d/sparky-stereo-deb-multimedia.sources" \
	"$D/etc/apt/preferences.d/sparky-stereo" "$D/etc/apt/preferences.d/sparky-stereo-only-ours"

# the messages of shadowed-by-dmo, word for word, as journal catalogs the engine reads in the person's language
mkdir -p "$D/usr/lib/systemd/catalog"
sparky-stereo-problems catalog "$PKG" "$HERE/lang" "$D/usr/lib/systemd/catalog" --subject LOCAL1
install -d "$D/usr/share/sparky/$PKG"
install -m644 "$HERE"/lang/* "$D/usr/share/sparky/$PKG/"

cat >"$D/usr/share/doc/$PKG/copyright" <<'EOS'
Sparky Stereo OS, Daniel Ramos's (Capitain Jack) edition of SparkyLinux (https://sparkylinux.org, by Paweł "pavroo" Pijanowski).

Upstream Author(s): 
    Paweł "pavroo" Pijanowski
    Daniel Ramos (Capitain Jack)

Files: * 
    Copyright (C) 2026 Paweł "pavroo" Pijanowski, Daniel Ramos (Capitain Jack)
    License: GPL-3

License:

    This package is free software; you can redistribute it and/or modify
    it under the terms of the GNU General Public License as published by
    the Free Software Foundation; either version 3 of the License, or
    (at your option) any later version.
 
    This package is distributed in the hope that it will be useful,
    but WITHOUT ANY WARRANTY; without even the implied warranty of
    MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
    GNU General Public License for more details.
 
    You should have received a copy of the GNU General Public License
    along with this package; if not, see <http://www.gnu.org/licenses/>.

On Debian systems, the complete text of the GNU General Public License
version 3 can be found in "/usr/share/common-licenses/GPL-3".
EOS
install -m644 "$HERE/README.md" "$D/usr/share/doc/$PKG/README.md"
chmod 644 "$D/usr/share/doc/$PKG/copyright"
find "$D" -type d -exec chmod 755 {} +

SIZE=$(du -sk --exclude=DEBIAN "$D" | cut -f1)
cat >"$D/DEBIAN/control" <<EOS
Package: $PKG
Version: $VERSION
Architecture: all
Maintainer: Daniel Ramos (Capitain Jack) <Capitain_Jack@yahoo.com>
Installed-Size: $SIZE
Depends: apt (>= 3.3.6), python3, python3-apt, sparky-stereo-problems (>= 0.1.2), sparky-apt, sparky-stereo-keyring (>= $KEYRING_VERSION), deb-multimedia-keyring
Section: System
Priority: optional
Homepage: https://sparkylinux.org
Description: Sparky Stereo OS apt source
  The apt source and pin of the Sparky Stereo OS package repository
  (https://repo.sparkyos.org/, codename mashtabba). The edition is built on
  SparkyLinux testing, so SparkyLinux's own repository comes with it, and on
  deb-multimedia's FFmpeg and mpv sources, so deb-multimedia's repository too.
  It also tells, on a metered connection and before apt asks to continue, which
  packages download data while they are installed, with the size and the source.
EOS
printf '%s\n' /etc/apt/sources.list.d/sparky-stereo.sources /etc/apt/sources.list.d/sparky-stereo-deb-multimedia.sources \
	/etc/apt/preferences.d/sparky-stereo /etc/apt/preferences.d/sparky-stereo-only-ours \
	/etc/apt/apt.conf.d/60sparky-stereo-appstream-icons \
	/etc/apt/apt.conf.d/61sparky-install-downloads /etc/dpkg/dpkg.cfg.d/sparky-stereo-apt >"$D/DEBIAN/conffiles"
install -m755 "$HERE/debian-scripts/preinst" "$HERE/debian-scripts/postinst" "$HERE/debian-scripts/postrm" "$D/DEBIAN/"
(cd "$D" && find . -path ./DEBIAN -prune -o -type f -print | sed 's|^\./||' | sort | tr '\n' '\0' | xargs -0 md5sum >DEBIAN/md5sums)
mkdir -p "$OUT"
mkdir -p "$W/authoring"
COPY="$HERE/../../../tools/copy-recipe.py"
python3 "$COPY" "$HERE" "$W/authoring"
python3 "$COPY" "$HERE/../../apt" "$W/authoring/apt-generator"
mkdir -p "$W/authoring/build-tools"
cp "$COPY" "$W/authoring/build-tools/"
PYTHONPATH="$HERE/../..${PYTHONPATH:+:$PYTHONPATH}" python3 -m lean.standalone "$D" "$OUT" --authoring "$W/authoring"
