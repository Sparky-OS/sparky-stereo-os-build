# Builds sparky-stereo-console, Daniel's console touches for Sparky Stereo OS:
#   /etc/issue, /etc/issue.net   his ASCII art (base/*.client, 2019), edition line
#                                "Sparky Stereo OS", live system details from getty
#   /etc/motd                    his Sparky wording of Debian's no-warranty notice
#   /etc/update-motd.d/10-uname  "Sparky Stereo OS based on" + uname -osnrvm
#   SSH banner                   sshd_config.d drop-in: Banner /etc/issue.net
#   /etc/skel/.bash_aliases      read by Debian's skel .bashrc ("put all your additions into a separate file like
#                                ~/.bash_aliases"): the coloured prompt forced on (the Linux console too), red for
#                                root, grep, dir and vdir in colour, GCC's colours, nano as EDITOR and VISUAL
#   fastfetch                    the neofetch layout with the Sparky leaf; `neofetch` runs it
#   command-not-found            a dependency; its index is filled at build time and by its own apt update hook; bash and fish
#                                call it already (Debian's /etc/bash.bashrc, fish's own handler); zsh does not, so /etc/zsh/zshrc is
#                                diverted and ours sources Debian's, then /etc/zsh_command_not_found (ORDER 251)
# Debian's /etc/issue, /etc/issue.net, 10-uname, nanorc and zshrc are diverted to *.debian (their owners offer no
# place of their own for these; rows 629/802) and given back when the package is removed. A diversion is added
# before its owner's conffile may be installed: the preinst moves the owner's pending PATH.dpkg-new to the diverted
# name, so our file at PATH never replaces it (Debian Policy, appendix 7: "dpkg does not handle it well").
# Up to 20261102 the skel .bashrc was diverted too; the postinst gives bash's own back (rows 629/802).
# Last update 2026/11/21
# Workstation paths come from the local configuration: sparky-os/config/build.conf.example.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-${SPARKY_REPO_DIR:?}}
VERSION=20261121.1~sparky9~0+lc1
PKG=sparky-stereo-console
B=$HERE/base
W=$(mktemp -d "${TMPDIR:-${SPARKY_SCRATCH:?}/sparky-os}/console-build.XXXXXX")
trap 'rm -rf "$W"' EXIT
D=$W/$PKG
S=$D/usr/share/$PKG
mkdir -p "$D/DEBIAN" "$D/etc/update-motd.d" "$D/etc/ssh/sshd_config.d" "$D/etc/skel" \
	"$D/etc/xdg/fastfetch" "$D/usr/bin" "$S" "$D/usr/share/doc/$PKG"

python3 - "$B" "$D" "$S" <<'PY'
import json, re, sys
b, d, s = sys.argv[1:4]
def rd(n): return open(f'{b}/{n}', encoding='utf-8').read()
def wr(p, t): open(p, 'w', encoding='utf-8').write(t)

# /etc/issue: the edition line (kept in its 29-column field, so the "debian" art beside
# it stays aligned) and live details from getty instead of a release typed by hand.
t = rd('issue.client')
t = t.replace('Small Business Client Edition', 'Stereo OS 9 "Mashtabba"'.ljust(29))
t = t.replace('/S /Debian GNU/Linux BullsEye', 'Sparky Stereo OS 9 "Mashtabba"')
t = re.sub(r'(`\$\$b\.\s+)\\v', lambda m: m.group(1) + 'based on Debian 14 "Forky"', t)
t = t.replace(r'\n \U', r'\n \r \m')
t = t.replace(r'(\l) SparkyLinux 5.7', r'(\l) \U  \4')
wr(f'{d}/etc/issue', t.rstrip('\n') + '\n\n')

# The Sparky leaf, from /etc/issue (the SSH version had some rows shifted): each row up to
# where the block letters or the "debian" art begin.
leaf = []
for l in rd('issue.client').split('\n')[1:19]:
    m = re.search(r'\s+(?:S+\b|\||/\||`\||_|Small)', l[20:])
    leaf.append((l[:20 + m.start()] if m else l).rstrip())
ind = min(len(l) - len(l.lstrip(' ')) for l in leaf if l.strip())
leaf = [l[ind:] for l in leaf]
wr(f'{s}/sparky-leaf.txt', '\n'.join(leaf) + '\n')

# /etc/issue.net (SSH shows it as plain text): the leaf centred over the 60-column block
# letters, then the edition line; "RESTRICTED" belongs to the business client.
w = max(len(l) for l in leaf)
net = [' ' * ((60 - w) // 2) + l for l in leaf]
blk = [l for l in rd('issue.net.client').split('\n') if l.startswith((' SSS', 'S ', '    S', 'SSSS'))]
assert len(blk) == 5, blk
net += blk + [' ' * ((60 - 23) // 2) + 'Stereo OS 9 "Mashtabba"', ' ' * ((60 - 26) // 2) + 'based on Debian 14 "Forky"']
wr(f'{d}/etc/issue.net', '\n'.join(net) + '\n\n')

wr(f'{d}/etc/motd', rd('motd.client').strip('\n') + '\n')

wr(f'{d}/etc/skel/.selected_editor', '# Generated by Sparky Stereo OS: nano is the terminal editor\nSELECTED_EDITOR="/bin/nano"\n')

# nano in colour for every user and root: Debian's /etc/nanorc with its first interface palette switched on.
n = rd('nanorc.debian')
block = ['set titlecolor bold,white,blue', 'set promptcolor lightwhite,grey', 'set statuscolor bold,white,green',
         'set errorcolor bold,white,red', 'set spotlightcolor black,lightyellow', 'set selectedcolor lightwhite,#804',
         'set stripecolor ,#444', 'set scrollercolor slate,#222', 'set numbercolor cyan', 'set keycolor cyan',
         'set functioncolor green']
first = '# ' + block[0]
assert n.count(first) == 1
i = n.index(first)
for line in block:
    assert n.find('# ' + line, i) >= 0, line
    n = n[:i] + n[i:].replace('# ' + line, line, 1)
n = n.replace(block[0], '## Sparky Stereo OS: nano in colour (Daniel, 2026-10-14: "coloured nano would be great")\n' + block[0], 1)
assert 'include "/usr/share/nano/*.nanorc"' in n and '\n# include "/usr/share/nano/*.nanorc"' not in n
wr(f'{d}/etc/nanorc', n)

# fastfetch: Debian's neofetch preset with the Sparky leaf as the logo.
c = rd('neofetch.jsonc.fastfetch')
c = re.sub(r'^\s*//.*$', '', c, flags=re.M)
j = json.loads(c)
j['logo'] = {'type': 'file', 'source': '/usr/share/sparky-stereo-console/sparky-leaf.txt'}
wr(f'{d}/etc/xdg/fastfetch/config.jsonc', json.dumps(j, indent=4, ensure_ascii=False) + '\n')
PY

# Debian's skel .bashrc reads ~/.bash_aliases after it has made the prompt and the ls alias, so a new account gets
# what our own copy of that .bashrc gave up to 20261102, with bash's .bashrc left as bash ships it (rows 629/802).
# Sparky Stereo OS (Daniel, 2026-10-14: "I love colored console", "my editor of choice in terminal is nano"): the file
# lands in every new account's home, so it says only what its lines do.
cat >"$D/etc/skel/.bash_aliases" <<'BASH'
# Sparky Stereo OS: read by Debian's ~/.bashrc, after it has made the prompt.
# The coloured prompt on every terminal, the Linux console too (force_color_prompt=yes in ~/.bashrc does the same):
# green for users, red for root.
if [ "$(id -u)" -eq 0 ]; then _user_colour=31; else _user_colour=32; fi
if [ -x /usr/bin/tput ] && tput setaf 1 >&/dev/null; then
    PS1='${debian_chroot:+($debian_chroot)}\[\033[01;${_user_colour}m\]\u@\h\[\033[00m\]:\[\033[01;34m\]\w\[\033[00m\]\$ '
else
    PS1='${debian_chroot:+($debian_chroot)}\u@\h:\w\$ '
fi
case "$TERM" in
xterm*|rxvt*)
    PS1="\[\e]0;${debian_chroot:+($debian_chroot)}\u@\h: \w\a\]$PS1"
    ;;
esac
# grep, dir and vdir in colour, GCC's colours, nano as the terminal editor.
if [ -x /usr/bin/dircolors ]; then
    alias dir='dir --color=auto'
    alias vdir='vdir --color=auto'
    alias grep='grep --color=auto'
    alias fgrep='fgrep --color=auto'
    alias egrep='egrep --color=auto'
fi
export GCC_COLORS='error=01;31:warning=01;35:note=01;36:caret=01;32:locus=01:quote=01'
export EDITOR=nano VISUAL=nano
BASH
chmod 644 "$D/etc/skel/.bash_aliases"
printf '#!/bin/sh\necho "Sparky Stereo OS 9 \\"Mashtabba\\", based on Debian 14 \\"Forky\\""\nuname -osnrvm\n' >"$D/etc/update-motd.d/10-uname"
printf '# Sparky Stereo OS: the SSH login banner\nBanner /etc/issue.net\n' >"$D/etc/ssh/sshd_config.d/sparky-stereo-banner.conf"
printf '#!/bin/sh\n# neofetch left Debian; fastfetch, its successor, runs in the neofetch layout\nexec fastfetch "$@"\n' >"$D/usr/bin/neofetch"
chmod 755 "$D/etc/update-motd.d/10-uname" "$D/usr/bin/neofetch"
chmod 644 "$D/etc/skel/.selected_editor" "$D/etc/nanorc"

mkdir -p "$D/etc/zsh"
cat >"$D/etc/zsh/zshrc" <<'ZSH'
# Sparky Stereo OS: Debian's own zshrc, then command-not-found, so a missing command names its package in zsh as it does in bash and fish
[[ -r /etc/zsh/zshrc.debian ]] && source /etc/zsh/zshrc.debian
[[ -r /etc/zsh_command_not_found ]] && source /etc/zsh_command_not_found
ZSH
chmod 644 "$D/etc/zsh/zshrc"
DIVERTED="/etc/issue /etc/issue.net /etc/update-motd.d/10-uname /etc/nanorc /etc/zsh/zshrc"
GIVEN_BACK=/etc/skel/.bashrc
sed -e "s|@DIVERTED@|$DIVERTED|" -e "s|@GIVEN_BACK@|$GIVEN_BACK|" "$HERE/preinst.in" >"$D/DEBIAN/preinst"
# 20261102 and older diverted $GIVEN_BACK; dpkg has removed our copy at this unpack, so bash's own goes back to its
# name with whatever the person changed in it. In the postinst: a preinst removal would make dpkg delete bash's
# file as one our old version shipped (measured, rows 629/802).
cat >"$D/DEBIAN/postinst" <<EOF
#!/bin/sh
# postinst script
set -e
if [ "\$1" = "configure" ]; then
	for f in $GIVEN_BACK; do
		if [ "\$(dpkg-divert --listpackage "\$f")" = $PKG ]; then
			dpkg-divert --quiet --package $PKG --remove --rename --divert "\$f.debian" "\$f"
		fi
	done
fi
exit 0
EOF
sed "s|@DIVERTED@|$DIVERTED $GIVEN_BACK|" "$HERE/postrm.in" >"$D/DEBIAN/postrm"
chmod 755 "$D/DEBIAN/preinst" "$D/DEBIAN/postinst" "$D/DEBIAN/postrm"
printf '%s\n' /etc/ssh/sshd_config.d/sparky-stereo-banner.conf /etc/xdg/fastfetch/config.jsonc >"$D/DEBIAN/conffiles"

cat >"$D/usr/share/doc/$PKG/copyright" <<'EOF'
