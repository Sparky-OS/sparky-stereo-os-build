"""The system locale may be absent or contain only update-locale's comment."""
import ast
import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

RECIPE = Path(__file__).resolve().parents[1]
TREE = RECIPE.parents[1]


class SystemLanguageTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        tree = ast.parse((RECIPE / 'bin/languages').read_text())
        tree.body = [node for node in tree.body if isinstance(node, ast.FunctionDef)
                     and node.name in ('select', 'system_language')]
        cls.functions = compile(tree, 'bin/languages', 'exec')
        manifest = TREE / 'lists/language-tasks.json'
        if not manifest.exists():
            manifest = RECIPE.parent / 'tree/usr/share/sparky-stereo-language-tasks/manifest.json'
        cls.rows = {r['code'].lower(): r for r in
                    json.loads(manifest.read_text())['languages']}

    def read_language(self, content, environment):
        with tempfile.TemporaryDirectory() as directory:
            locale = Path(directory) / 'locale'
            if content is not None:
                locale.write_text(content)
            namespace = {'Path': lambda name: locale, 'os': os, 'ROWS': self.rows}
            exec(self.functions, namespace)
            with patch.dict(os.environ, environment, clear=True):
                return namespace['system_language']()

    def test_missing_empty_and_comment_only_follow_environment(self):
        for content in (None, '', '#  File generated by update-locale\n'):
            for environment, expected in (({}, 'en'), ({'LANG': 'C.UTF-8'}, 'en'),
                                          ({'LANG': 'pt_BR.UTF-8'}, 'pt-br')):
                with self.subTest(content=content, environment=environment):
                    self.assertEqual(self.read_language(content, environment), expected)

    def test_explicit_portuguese_wins(self):
        self.assertEqual(self.read_language('LANG="pt_BR.UTF-8"\n', {'LANG': 'en_US.UTF-8'}), 'pt-br')

    def test_unsupported_explicit_locale_is_rejected(self):
        with self.assertRaises(ValueError):
            self.read_language('LANG=zz_ZZ.UTF-8\n', {'LANG': 'en_US.UTF-8'})


if __name__ == '__main__':
    unittest.main()
