"""make_edid.py OUTDIR : builds the test EDID of the edid3d test (256 bytes: an EDID 1.4 base block and a CTA-861 extension with an HDMI 1.4 vendor specific data block
that declares 3D support) and writes edid.bin, edid_blob.h (for the module) and expect.json (what a correct parser must list, worked out here from the HDMI 1.4b rules, not from
the kernel's code).

Video data block (CTA-861 order): VIC 16 (1080p60, native), 4 (720p60), 19 (720p50), 32 (1080p24), 31 (1080p50).
HDMI VSDB: HDMI_Video_present, 3D_present, 3D_Multi_present = 2 (3D_Structure_ALL and 3D_MASK follow),
  3D_Structure_ALL = bit 0 frame packing | bit 3 side-by-side (full) | bit 6 top-and-bottom | bit 8 side-by-side (half) = 0x0149,
  3D_MASK = 0x0003 = the first two VICs of the video data block (16 and 4).
What HDMI 1.4b then requires a parser to list:
  declared: 1920x1080p60 and 1280x720p60, each as frame packing, side-by-side (full), top-and-bottom, side-by-side (half);
  mandatory formats of a 3D sink whose 2D mode is present: 1080p24 FP and TB, 720p50 FP and TB, 720p60 FP and TB (the 720p60 ones are declared as well).
"""
import json, os, sys

def checksum_fix(b):
    b = bytearray(b)
    b[127] = (-sum(b[:127])) & 0xFF
    return bytes(b)

def base_block():
    b = bytearray(128)
    b[0:8] = bytes([0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00])
    mid = ((ord('T') - 64) << 10) | ((ord('S') - 64) << 5) | (ord('T') - 64)   # manufacturer "TST"
    b[8], b[9] = mid >> 8, mid & 0xFF
    b[10], b[11] = 0x01, 0x00            # product code
    b[16], b[17] = 1, 36                 # week 1 of 2026
    b[18], b[19] = 1, 4                  # EDID 1.4
    b[20] = 0xA2                         # digital, 8 bpc, HDMI-a
    b[21], b[22] = 48, 27                # 48 x 27 cm
    b[23] = 0x78                         # gamma 2.2
    b[24] = 0x0A                         # RGB 4:4:4, preferred timing is native
    b[25:35] = bytes([0xEE, 0x91, 0xA3, 0x54, 0x4C, 0x99, 0x26, 0x0F, 0x50, 0x54])   # chromaticity (sRGB)
    b[38:54] = bytes([0x01, 0x01] * 8)   # no standard timings
    # detailed timing 1: 1920x1080 @ 60 Hz, 148.5 MHz
    b[54:72] = bytes([0x02, 0x3A, 0x80, 0x18, 0x71, 0x38, 0x2D, 0x40, 0x58, 0x2C, 0x45, 0x00, 0xE0, 0x0E, 0x11, 0x00, 0x00, 0x1E])
    name = b"EDID3D TEST\n"
    b[72:90] = bytes([0, 0, 0, 0xFC, 0]) + name + bytes([0x20])           # monitor name
    b[90:108] = bytes([0, 0, 0, 0xFD, 0, 24, 75, 30, 83, 15, 0, 0x0A, 0x20, 0x20, 0x20, 0x20, 0x20, 0x20])   # range limits
    b[108:126] = bytes([0, 0, 0, 0x10, 0]) + bytes(13)                    # dummy
    b[126] = 1                           # one extension block
    return checksum_fix(b)

def cta_block():
    b = bytearray(128)
    vdb = bytes([0x40 | 5, 0x90, 0x04, 0x13, 0x20, 0x1F])               # VIC 16 (native), 4, 19, 32, 31
    vsdb = bytes([0x60 | 14,
                  0x03, 0x0C, 0x00,                                      # HDMI 1.4 OUI 00-0C-03
                  0x10, 0x00,                                            # source physical address 1.0.0.0
                  0x00,                                                  # no deep colour
                  0x1E,                                                  # max TMDS clock 150 MHz
                  0x20,                                                  # HDMI_Video_present (no latency fields)
                  0xC0,                                                  # 3D_present, 3D_Multi_present = 2
                  0x04,                                                  # HDMI_VIC_LEN 0, HDMI_3D_LEN 4
                  0x01, 0x49,                                            # 3D_Structure_ALL
                  0x00, 0x03])                                           # 3D_MASK
    assert len(vsdb) == 15
    b[0], b[1] = 0x02, 0x03
    blocks = vdb + vsdb
    b[2] = 4 + len(blocks)               # offset of the detailed timings (none)
    b[3] = 0x00
    b[4:4 + len(blocks)] = blocks
    return checksum_fix(b)

FP, SBSF, TB, SBSH = 1, 4, 7, 8          # DRM_MODE_FLAG_3D_* >> 14
def expected():
    exp = set()
    for (w, h, hz, il) in ((1920, 1080, 60, 0), (1280, 720, 60, 0)):
        for s in (FP, SBSF, TB, SBSH):
            exp.add((w, h, hz, il, s))
    for (w, h, hz, il) in ((1920, 1080, 24, 0), (1280, 720, 50, 0), (1280, 720, 60, 0)):
        for s in (FP, TB):
            exp.add((w, h, hz, il, s))
    return sorted(exp)

if __name__ == '__main__':
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    edid = base_block() + cta_block()
    assert len(edid) == 256 and sum(edid[:128]) % 256 == 0 and sum(edid[128:]) % 256 == 0
    open(os.path.join(out, 'edid.bin'), 'wb').write(edid)
    with open(os.path.join(out, 'edid_blob.h'), 'w') as f:
        f.write('/* generated by make_edid.py: the test EDID of the edid3d test */\nstatic const unsigned char edid_blob[256] = {\n')
        for i in range(0, 256, 16):
            f.write('\t' + ', '.join('0x%02x' % x for x in edid[i:i + 16]) + ',\n')
        f.write('};\n')
    json.dump({'3d_codes': {'1': 'frame packing', '4': 'side by side (full)', '7': 'top and bottom', '8': 'side by side (half)'},
               'expected_3d_modes': [list(e) for e in expected()]}, open(os.path.join(out, 'expect.json'), 'w'), indent=1)
    print('edid.bin %d bytes, %d expected 3D modes' % (len(edid), len(expected())))
