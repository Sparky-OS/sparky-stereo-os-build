"""Check kernel text generators against the retained authored-input baseline.

C token equivalence does not cover these Perl readers: error mappings and
class boundaries are stored in comments. SMB2 can return success with an empty
table. OID identifiers and CPU feature names also live in comments. Compare
generated bytes and reject empty registries before native compilation.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

CASES = [
    ('fs/smb/client/gen_smb1_mapping', 'fs/smb/client/nterr.h', 'smb1_mapping_table.c'),
    ('fs/smb/client/gen_smb1_mapping', 'fs/smb/client/smberr.h', 'smb1_err_dos_map.c'),
    ('fs/smb/client/gen_smb1_mapping', 'fs/smb/client/smberr.h', 'smb1_err_srv_map.c'),
    ('fs/smb/client/gen_smb2_mapping', 'fs/smb/common/smb2status.h', 'smb2_mapping_table.c'),
]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def measure(root):
    results = []
    with tempfile.TemporaryDirectory(prefix='kernel-source-consumers-') as temporary:
        for generator, header, output in CASES:
            destination = Path(temporary) / output
            subprocess.run(['perl', str(root / generator), str(root / header),
                            str(destination)], check=True)
            data = destination.read_bytes()
            entries = sum(line.lstrip().startswith(b'{') for line in data.splitlines())
            if not entries:
                raise ValueError('Generator returned an empty mapping table: ' + output)
            results.append(dict(generator=generator, input=header, output=output,
                generator_sha256=sha((root / generator).read_bytes()),
                input_sha256=sha((root / header).read_bytes()),
                output_sha256=sha(data), entries=entries))
        generator, header, output = ('lib/build_OID_registry',
                                    'include/linux/oid_registry.h',
                                    'oid_registry_data.c')
        destination = Path(temporary) / output
        subprocess.run(['perl', generator, header, str(destination)], cwd=root,
                       env=dict(os.environ, srctree=str(root)), check=True)
        data = destination.read_bytes()
        names = set(re.findall(rb'^\s*\[(OID_[A-Za-z0-9_]+)\]\s*=', data, re.M))
        names.discard(b'OID__NR')
        if not {b'OID_data', b'OID_signed_data', b'OID_sha256'} <= names:
            raise ValueError('OID registry lacks required cryptographic identifiers')
        results.append(dict(generator=generator, input=header, output=output,
            generator_sha256=sha((root / generator).read_bytes()),
            input_sha256=sha((root / header).read_bytes()),
            output_sha256=sha(data), entries=len(names)))

        generator = 'arch/x86/kernel/cpu/mkcapflags.sh'
        headers = ['arch/x86/include/asm/cpufeatures.h',
                   'arch/x86/include/asm/vmxfeatures.h']
        output = 'capflags.c'
        destination = Path(temporary) / output
        subprocess.run(['sh', generator, str(destination), *headers], cwd=root, check=True)
        data = destination.read_bytes()
        counts = {prefix: len(re.findall(rb'^\s*\[' + prefix.encode() + rb'[A-Za-z0-9_]+',
                                        data, re.M))
                  for prefix in ['X86_FEATURE_', 'X86_BUG_', 'VMX_FEATURE_']}
        if not all(counts.values()):
            raise ValueError('CPU capability registry contains an empty feature-name group')
        results.append(dict(generator=generator, output=output,
            generator_sha256=sha((root / generator).read_bytes()),
            inputs={header: sha((root / header).read_bytes()) for header in headers},
            output_sha256=sha(data), entries=sum(counts.values()), groups=counts))
    return dict(schema=2, cases=results)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['record', 'check'])
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    root = args.source.resolve()
    manifest = root / 'debian/kernel-source-consumers.json'
    if args.action == 'record':
        if manifest.exists() or (root / '.sparky-lc').exists():
            raise ValueError('Record only once, from a fresh authored source export')
        actual = measure(root)
        manifest.write_text(json.dumps(actual, indent=2) + '\n')
    else:
        expected = json.loads(manifest.read_text())
        actual = measure(root)
        if actual != expected:
            raise ValueError('Kernel source consumer differs from its authored baseline')
    for case in actual['cases']:
        print(case['output'], case['entries'], 'entries', case['output_sha256'])


if __name__ == '__main__':
    main()
